import AppKit

/// Types text into the focused app by pasting it, then restores the clipboard.
/// Requires the Accessibility permission (to send ⌘V).
@MainActor
public enum TextInserter {
    /// Asks clipboard managers not to record our temporary clipboard contents
    /// (see nspasteboard.org).
    private static let markerTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let vKeyCode: CGKeyCode = 9

    public static func insert(_ text: String, restoreAfter delay: Duration = .milliseconds(400)) async {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in markerTypes { item.setData(Data(), forType: type) }
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        pressCommandV()

        // Give the target app time to read the clipboard, then put the person's
        // clipboard back — unless something else has written to it meanwhile.
        try? await Task.sleep(for: delay)
        guard pasteboard.changeCount == ourChange else { return }
        pasteboard.clearContents()
        if !saved.isEmpty { pasteboard.writeObjects(saved) }
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }
}
